"""Compile src/predictygraph/themes/*.toml and default.css into web/src/themes.gen.ts.

Run: make themes   (PDG_SRC=path/to/predictygraph checkout)
"""

import json
import os
import tomllib
from pathlib import Path

PKG = Path(os.environ.get("PDG_SRC", "../predictygraph")).resolve() / "src" / "predictygraph"
OUT = Path(__file__).resolve().parents[1] / "src" / "themes.gen.ts"


def load(name: str) -> dict:
    data = tomllib.loads((PKG / "themes" / f"{name}.toml").read_text(encoding="utf-8"))
    if "extends" not in data:
        return data
    parent = load(data["extends"])
    for sect in ("palette", "roles", "shape"):
        parent.setdefault(sect, {}).update(data.get(sect, {}))
    if "css" in data:
        parent["css"] = parent.get("css", "") + "\n" + data["css"]
    parent["dark"] = data.get("dark", parent.get("dark", False))
    return parent


themes = {p.stem: {k: v for k, v in load(p.stem).items() if k in ("palette", "roles", "shape", "css")} for p in sorted((PKG / "themes").glob("*.toml"))}
OUT.write_text(
    "// generated by scripts/gen_themes.py; do not edit\n"
    'import type { ThemeData } from "./theme.ts";\n\n'
    f"export const THEMES: Record<string, ThemeData> = {json.dumps(themes, indent=2)};\n\n"
    f"export const BUILTIN_CSS = {json.dumps((PKG / 'default.css').read_text())};\n"
)
print(f"wrote {OUT} ({len(themes)} themes)")
